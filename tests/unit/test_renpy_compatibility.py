def test_activation_hook_prevents_multiple_wrapping():
    """Verify reload protection: Text.set_text is not recursively wrapped on script reload."""
    calls = []

    class MockText:
        @staticmethod
        def set_text(self, text, *args, **kwargs):
            calls.append(("orig", text))
            return text

    # First installation
    if not hasattr(MockText, "_gl_orig_set_text"):
        MockText._gl_orig_set_text = MockText.set_text

        def _gl_set_text(self, text, *args, **kwargs):
            calls.append(("hook", text))
            return MockText._gl_orig_set_text(self, text, *args, **kwargs)

        MockText.set_text = _gl_set_text

    assert hasattr(MockText, "_gl_orig_set_text")
    first_hook = MockText.set_text

    # Simulated script reload (Shift+R)
    if not hasattr(MockText, "_gl_orig_set_text"):
        MockText._gl_orig_set_text = MockText.set_text
        MockText.set_text = lambda self, text, *a, **kw: None

    # Must retain original single-level wrapper without re-wrapping
    assert MockText.set_text is first_hook

    MockText.set_text(MockText(), "test")
    assert calls == [("hook", "test"), ("orig", "test")]


def test_activation_hook_signature_variations():
    """Verify *args and **kwargs correctly support varying Ren'Py method signatures."""
    captured_args = {}

    class MockTextRenPy7:
        @staticmethod
        def set_text(self, text, scope=None, substitute=False):
            captured_args["engine"] = "renpy7"
            captured_args["scope"] = scope
            captured_args["substitute"] = substitute
            return text

    class MockTextRenPy8:
        @staticmethod
        def set_text(self, text, scope=None, substitute=False, update=True):
            captured_args["engine"] = "renpy8"
            captured_args["scope"] = scope
            captured_args["substitute"] = substitute
            captured_args["update"] = update
            return text

    # Wrap Ren'Py 7 style
    orig_r7 = MockTextRenPy7.set_text

    def hook_r7(self, text, *args, **kwargs):
        return orig_r7(self, text, *args, **kwargs)

    hook_r7(MockTextRenPy7(), "hello", scope={"a": 1}, substitute=True)
    assert captured_args["engine"] == "renpy7"
    assert captured_args["scope"] == {"a": 1}
    assert captured_args["substitute"] is True

    # Wrap Ren'Py 8 style
    orig_r8 = MockTextRenPy8.set_text

    def hook_r8(self, text, *args, **kwargs):
        return orig_r8(self, text, *args, **kwargs)

    hook_r8(MockTextRenPy8(), "hello", scope=None, substitute=False, update=False)
    assert captured_args["engine"] == "renpy8"
    assert captured_args["update"] is False


