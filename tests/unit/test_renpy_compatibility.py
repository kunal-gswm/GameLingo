def test_activation_script_syntax_and_headers():
    """Verify generated activation script headers and Python 2/3 universal syntax."""
    script = generate_activation_rpy("english")

    # PEP 263 encoding declaration for Python 2.7
    assert script.startswith("# -*- coding: utf-8 -*-")
    assert "Translation activation generated by GameLingo" in script
    assert (
        "Compatible with Ren'Py 7.x (Python 2.7) and Ren'Py 8.x (Python 3)." in script
    )
    assert 'config.default_language = "english"' in script
    assert 'default preferences.language = "english"' in script

    # Check the Python code block parses as valid Python syntax
    # Extract python code within init blocks
    py_lines = []
    in_py = False
    for line in script.splitlines():
        if line.startswith("init") and "python:" in line:
            in_py = True
            continue
        if in_py:
            if line.startswith("default ") or (
                line and not line.startswith(" ") and not line.startswith("#")
            ):
                in_py = False
            else:
                py_lines.append(line)

    py_code = textwrap.dedent("\n".join(py_lines))
    # Parse with Python AST to verify syntax validity
    parsed_ast = ast.parse(py_code)
    assert parsed_ast is not None

    # Verify absence of Python 3-only syntax constructs in the generated code
    for node in ast.walk(parsed_ast):
        # No f-strings (JoinedStr)
        assert not isinstance(node, ast.JoinedStr), (
            "Generated script must not contain f-strings"
        )
        # No walrus operator (NamedExpr)
        assert not isinstance(node, getattr(ast, "NamedExpr", type(None))), (
            "Generated script must not contain walrus :="
        )
        # No function type annotations
        if isinstance(node, ast.FunctionDef):
            assert node.returns is None, (
                "Generated script must not contain return type annotations"
            )
            for arg in node.args.args:
                assert arg.annotation is None, (
                    "Generated script must not contain argument annotations"
                )


def test_activation_hook_py2_py3_string_type_simulation():
    """Simulate string type checking in both Python 2.7 (unicode/str) and Python 3.x (str)."""
    translations = {"今日をどう使う——": "How to spend today——"}

    def mock_translate(s: str) -> str:
        return translations.get(s, s)

    # 1. Python 3 simulation: unicode raises NameError -> _gl_string_types = (str,)
    try:
        raise NameError("name 'unicode' is not defined")
    except NameError:
        py3_string_types = (str,)

    text_py3 = "今日をどう使う——"
    assert isinstance(text_py3, py3_string_types)
    assert mock_translate(text_py3) == "How to spend today——"

    # 2. Python 2 simulation: str and unicode are distinct types
    class MockUnicode(str):
        pass

    py2_string_types = (str, MockUnicode)
    text_py2_unicode = MockUnicode("今日をどう使う——")
    assert isinstance(text_py2_unicode, py2_string_types)
    assert mock_translate(text_py2_unicode) == "How to spend today——"


def test_activation_hook_repeated_rendering_idempotency():
    """Verify repeated rendering across screen update cycles does not cause double translation."""
    translations = {
        "採取量": "Harvest Yield",
        "男を狩る": "Hunt Men",
    }

    def mock_translate(s: str) -> str:
        return translations.get(s, s)

    def hook(text):
        if isinstance(text, (str,)):
            return mock_translate(text)
        return text

    # First render
    rendered_1 = hook("採取量")
    assert rendered_1 == "Harvest Yield"

    # Second render with the already-translated string (e.g. screen redraw)
    rendered_2 = hook(rendered_1)
    assert rendered_2 == "Harvest Yield"

    # Third render
    rendered_3 = hook(rendered_2)
    assert rendered_3 == "Harvest Yield"


