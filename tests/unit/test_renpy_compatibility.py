def test_activation_hook_list_of_segments():
    """Verify lists with mixed string, integer, and tuple items are translated safely."""
    translations = {"採取量": "Harvest Yield"}

    def hook(text):
        if isinstance(text, list):
            return [translations.get(x, x) if isinstance(x, str) else x for x in text]
        return text

    segments = ["採取量", ": ", 100, ("tag", "param")]
    result = hook(segments)
    assert result == ["Harvest Yield", ": ", 100, ("tag", "param")]


